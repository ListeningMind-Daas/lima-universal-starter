def classify_keywords(all_kws: list[str]) -> dict[str, dict[str, list[str]]]:
    """정규식 기반 · 각 W → 서브그룹 → 매칭 키워드 리스트."""
    result: dict[str, dict[str, list[str]]] = {}
    for w_key, subgroups in CEP_REGEX.items():
        subs_out = {}
        for sub_label, patterns in subgroups.items():
            combined = "|".join(patterns)
            matched = [kw for kw in all_kws if re.search(combined, kw, re.IGNORECASE)]
            if matched:
                subs_out[sub_label] = matched
        if subs_out:
            result[w_key] = subs_out
    return result
